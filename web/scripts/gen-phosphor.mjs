import { readFileSync, writeFileSync, mkdirSync } from "fs";
const base = "node_modules/@phosphor-icons/web/src";
mkdirSync("src/styles/generated", { recursive: true });
let out = `// Generated by scripts/gen-phosphor.mjs — do not edit.
// Stripped-down mirror of @phosphor-icons/web bold/fill style.css: identical
// class rules, but each @font-face keeps only its woff2 src so the woff/ttf/
// svg fallbacks (~1.3 MB, never downloaded) stay out of dist.

`;
for (const weight of ["bold", "fill"]) {
  const css = readFileSync(`${base}/${weight}/style.css`, "utf8");
  const stripped = css
    .replace(
      /,\s*url\("\.\/Phosphor-[^"]*"\)\s*format\("(?:woff|truetype|svg)"\)/g,
      ""
    )
    // The two woff2 files are vendored copies in src/assets/fonts/
    // (refreshed by this script); a root-absolute url (Vite project-root
    // alias) keeps the asset inside Vite's CSS graph, hashed and emitted.
    .replace(
      /url\("\.\/Phosphor-(Bold|Fill)\.woff2"\)/g,
      'url("/src/assets/fonts/Phosphor-$1.woff2")'
    );
  out += `/* ==== ${weight} ==== */\n${stripped}\n`;
}
writeFileSync("src/styles/generated/_phosphor.scss", out);
console.log("gen-phosphor: wrote src/styles/generated/_phosphor.scss");

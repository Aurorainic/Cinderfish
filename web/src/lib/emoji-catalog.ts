const RECENT_KEY = "cinderfish.recent-emojis";
const RECENT_LIMIT = 16;

function readRecent(): string[] {
  try {
    const raw = JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]") as unknown;
    if (!Array.isArray(raw)) return [];
    return raw.filter((item): item is string => typeof item === "string").slice(0, RECENT_LIMIT);
  } catch {
    return [];
  }
}

// Module-level state: every picker in the app shares one "recent" list, and
// the persisted list is read once when the module is first imported.
const recentEmojis = ref<string[]>(readRecent());

/** The recently used reactions, newest first, plus a way to record one. */
export function useRecentEmojis(): { recent: Ref<string[]>; push(char: string): void } {
  function push(char: string): void {
    if (!char) return;
    const next = [char, ...recentEmojis.value.filter((item) => item !== char)].slice(0, RECENT_LIMIT);
    recentEmojis.value = next;
    try {
      localStorage.setItem(RECENT_KEY, JSON.stringify(next));
    } catch {
      // Storage can be full or disabled; the in-memory list still works.
    }
  }

  return { recent: recentEmojis, push };
}

const ALL_EMOJIS: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((category) => category.emojis);

/** Name substring search, case-insensitive. An exact emoji character also
 * matches, so pasting a reaction finds its entry. */
export function searchEmojis(query: string, limit = 64): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const matches = ALL_EMOJIS.filter(
    (emoji) => emoji.name.includes(q) || emoji.char === query.trim(),
  );
  return matches.slice(0, limit);
}

/** Resolve a reaction to its shortcode name for tooltips and aria labels. */
export function emojiName(char: string): string {
  return ALL_EMOJIS.find((emoji) => emoji.char === char)?.name ?? char;
}

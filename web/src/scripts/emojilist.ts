const skinToneModifiers = ["", "🏻", "🏼", "🏽", "🏾", "🏿"];

export const emojilist: UnicodeEmojiDef[] = unicodeEmojiCategories.flatMap(
	(category) =>
		grouped[category].map(([emoji, slug, keywords]) => ({
			emoji,
			slug,
			category,
			skin_tone_support: skinToneSupport.has(slug),
			keywords: keywords == null || keywords === "" ? [] : keywords.split(" "),
		})),
);

const byEmoji = new Map(emojilist.map((def) => [def.emoji, def]));

/**
 * Firefish reads the tone list from `data-emoji-components.json`; here the
 * modifiers are inlined and unrelated emojis are returned unchanged.
 */
export function addSkinTone(emoji: string, skinTone?: number): string {
	const stripped = emoji.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "");
	const def = byEmoji.get(stripped);
	if (def == null || !def.skin_tone_support) return emoji;

	const tone = skinTone ?? 1;
	return stripped + (skinToneModifiers[tone] ?? "");
}

export function getNicelyLabeledCategory(internalName: string): string {
	return categoryLabels[internalName as UnicodeEmojiCategory] ?? internalName;
}
